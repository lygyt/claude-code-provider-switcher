Module._load = function(id, parent) {
  if (id === 'vscode') return vscode;
  if (parent?.filename.endsWith('sidebarChatBackend.js')) {
    if (id === 'node:child_process') return { spawn: (exe, args, options) => {
      spawnCount++; captured = { exe, args, options }; child = new EventEmitter(); child.stdin = new PassThrough(); child.stdout = new PassThrough(); child.stderr = new PassThrough(); child.kill = () => child.emit('close', 0); return child;
    }, execFile: (cmd, args, options, cb) => cb(null, '') };
    if (id === './claudeCli') return { resolveClaudeExecutable: async () => 'claude' };
    if (id === './terminalLauncher') return { buildClaudeTerminalEnv: () => ({ ANTHROPIC_API_KEY: 'test-key', ANTHROPIC_AUTH_TOKEN: null }), prepareSkillLaunchSelection: async selection => ({ ...selection, directories: ['aggregate'], autoUse: { ...selection.autoUse, slashName: 'resolved' } }) };
    if (id === './validation') return { authTypeRequiresToken: () => true };
    if (id === './vscodeUtils') return { getConfig: () => ({ permissionMode: 'requestApproval' }) };
  }
  return original.apply(this, arguments);
};
